import assert from 'node:assert/strict';
import {ccc} from '@ckb-ccc/core';
import {makeTradeAttempt,parseTradeAttempt,tradeKey} from '../lib/v2-engine/pudge-trade-journal.ts';
import {assertWalletFundingAvailable} from '../lib/v2-engine/wallet-pending.ts';
import {readFileSync,mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {marketNetwork} from '../lib/v2-engine/market-network-server.ts';
import {cccA} from '@ckb-ccc/core/advanced';
const fixture=JSON.parse(readFileSync(new URL('./fixtures/pudge-interleaved-sell.json',import.meta.url)));
const tx=ccc.Transaction.from(cccA.JsonRpcTransformers.transactionTo(fixture.transactions[fixture.sell].transaction));
const owner='0x'+tx.witnesses[5].slice(26,90),genesis='0x'+'ab'.repeat(32),market=tx.outputs[0].lock.hash();
const attempt=makeTradeAttempt(genesis,owner,tx,market);
assert.equal(parseTradeAttempt(JSON.stringify(attempt)).market,market);
assert.notEqual(tradeKey(genesis,owner,market),tradeKey(genesis,owner,'0x'+'ef'.repeat(32)));
assert.throws(()=>makeTradeAttempt(genesis,owner,tx,'0x'+'ef'.repeat(32)),/market mismatch/);
const values=new Map([[tradeKey(genesis,owner,market),JSON.stringify(attempt)]]);
const storage={get length(){return values.size},key:index=>[...values.keys()][index],getItem:key=>values.get(key)??null};
assert.throws(()=>assertWalletFundingAvailable(storage,genesis,owner),/reconciliation/);
values.clear();values.set(tradeKey(genesis,owner,market)+':settled','receipt');
assert.doesNotThrow(()=>assertWalletFundingAvailable(storage,genesis,owner));
const config=join(mkdtempSync(join(tmpdir(),'brant-network-')),'config.json');writeFileSync(config,'{}');
process.env.BRANT_ISOLATED_CONFIG=config;process.env.BRANT_ISOLATED_TEST='1';process.env.NODE_ENV='production';
assert.throws(()=>marketNetwork(),/disabled/);
console.log('PASS market-bound trade records, wallet-wide unresolved funding guard and production override rejection');
